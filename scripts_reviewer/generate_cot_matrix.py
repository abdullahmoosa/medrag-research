#!/usr/bin/env python3
"""
Generate the CoT+RAG matrix run script: the 9 configs that are consistent
across both embeddings (index_1/bge and medembed), for BOTH models
(base llama3:8b first, then med42), so base-vs-med42 CoT comparisons
replicate the zero-shot matrix.

Target grid (cot leaf for every config):
    dense  / {coarse_k20, coarse_off} / {reranker_off, on} / {no_reformulation, reformulation}
    hybrid / coarse_k20 / reranker_on / reformulation

Skip-guarded: configs with an existing full 1273-question run are skipped.
"""

from pathlib import Path

PY = "/home/ser/mambaforge/envs/medrag/bin/python"
MODELS = ["llama3:8b", "thewindmom/llama3-med42-8b:latest"]  # base first
INDEXES = {
    "index_1": "--index-dir /home/ser/medrag/processed_corpus --index-name index_1",
    "medembed": (
        "--index-dir /home/ser/medrag/processed_corpus_medembed --index-name medembed "
        "--embedding-model abhinand/MedEmbed-large-v0.1"
    ),
}

# (mode, coarse, reranker, reform) for the 9 consistent configs
GRID = (
    [("dense", c, r, f)
     for c in ("coarse_k20", "coarse_off")
     for r in ("reranker_off", "reranker_on")
     for f in ("no_reformulation", "reformulation")]
    + [("hybrid", "coarse_k20", "reranker_on", "reformulation")]
)


def flags(index: str, mode: str, coarse: str, reranker: str, reform: str) -> str:
    flags = f"--mode rag {INDEXES[index]} --retrieval-mode {mode} --use-cot"
    if coarse == "coarse_k20":
        flags += " --coarse-retrieval --coarse-top-k 20"
    if reranker == "reranker_on":
        flags += " --use-reranker"
    if reform == "reformulation":
        flags += " --use-reformulation"
    return flags


def output_rel(index: str, model_dir: str, mode: str, coarse: str, reranker: str, reform: str) -> str:
    return f"RAG/{index}/{mode}/{coarse}/{reranker}/{reform}/{model_dir}/cot"


def main() -> None:
    lines = [
        "#!/usr/bin/env bash",
        "# CoT+RAG matrix: the 9 cross-embedding-consistent configs x 2 indexes x 2 models.",
        "# Generated by scripts_reviewer/generate_cot_matrix.py -- do not edit by hand.",
        "set -u",
        f"PY={PY}",
        "cd /home/ser/medrag",
        "",
        "# Skip-check: exit 0 if this config already has a full 1273-question run",
        "is_done() { $PY -c \"import json,glob,sys; h=glob.glob(sys.argv[1]+'/**/metrics.json',recursive=True);"
        " sys.exit(0 if any(json.load(open(m)).get('total')==1273 for m in h) else 1)\" \"$1\"; }",
        "",
    ]
    n = 0
    total = len(MODELS) * len(INDEXES) * len(GRID)
    for model in MODELS:
        model_dir = "llama3_8b" if model == "llama3:8b" else "llama3_med42_8b"
        for index in INDEXES:
            for (mode, coarse, reranker, reform) in GRID:
                n += 1
                cfg = f"{index}/{mode}/{coarse}/{reranker}/{reform}/cot [{model_dir}]"
                out_rel = output_rel(index, model_dir, mode, coarse, reranker, reform)
                lines.append(f'echo "=== [{n}/{total}] {cfg} ==="')
                lines.append(
                    f'if is_done "evaluation_results/final_output/{out_rel}"; '
                    f'then echo "SKIP (done): {cfg}"'
                )
                lines.append(
                    f"else $PY -m src.rag_evaluation.cli {flags(index, mode, coarse, reranker, reform)} "
                    f"--llm-model {model} || echo 'FAILED: {cfg}'"
                )
                lines.append("fi")
                lines.append("")

    out = Path("/home/ser/medrag/run_cot_matrix.sh")
    out.write_text("\n".join(lines) + "\n")
    out.chmod(0o755)
    print(f"Wrote {total} commands to {out}")


if __name__ == "__main__":
    main()
