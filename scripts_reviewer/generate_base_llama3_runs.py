#!/usr/bin/env python3
"""
Generate the base-llama3 run script from the existing med42 results tree.

Walks evaluation_results/final_output, maps each unique med42 config directory
to its equivalent CLI flags, and emits one command per config (model swapped
to llama3:8b) into run_base_llama3.sh.

Dir-name -> flag mapping (mirrors cli.generate_output_dir):
    RAG/{index}/{mode}/{coarse}/{reranker}/{reformulation}/{model}/{cot}
      index_1    -> --index-dir processed_corpus           (bge-large default)
      medembed   -> --index-dir processed_corpus_medembed  (MedEmbed query encoder)
      coarse_kN  -> --coarse-retrieval --coarse-top-k N
      reranker_on-> --use-reranker
      reformulation -> --use-reformulation
      cot        -> --use-cot
    NO_RAG/{zero_shot|cot}/{model}
"""

import argparse
import re
from pathlib import Path

BASE = Path("/home/ser/medrag/evaluation_results/final_output")
MODEL = "llama3:8b"

INDEX_DIRS = {
    "index_1": ("--index-dir /home/ser/medrag/processed_corpus --index-name index_1", None),
    "medembed": (
        "--index-dir /home/ser/medrag/processed_corpus_medembed --index-name medembed "
        "--embedding-model abhinand/MedEmbed-large-v0.1",
        None,
    ),
}


def flags_for(rel: Path) -> str:
    """Map a config path (relative to final_output) to CLI flags."""
    parts = rel.parts
    if parts[0] == "NO_RAG":
        flags = "--mode no_rag"
        if parts[1] == "cot":
            flags += " --use-cot"
        return flags
    if parts[0] != "RAG":
        return ""
    index_name, mode, coarse, reranker, reform = parts[1:6]
    cot = parts[6]
    index_flags, _ = INDEX_DIRS[index_name]
    flags = f"--mode rag {index_flags} --retrieval-mode {mode}"
    m = re.fullmatch(r"coarse_k(\d+)", coarse)
    if m:
        flags += f" --coarse-retrieval --coarse-top-k {m.group(1)}"
    if reranker == "reranker_on":
        flags += " --use-reranker"
    if reform == "reformulation":
        flags += " --use-reformulation"
    if cot == "cot":
        flags += " --use-cot"
    return flags


def expected_output_dir(cfg: tuple) -> str:
    """Relative output dir the CLI will create for this config (model inserted)."""
    parts = list(cfg)
    if parts[0] == "NO_RAG":
        return "/".join(parts + ["llama3_8b"])
    return "/".join(parts[:6] + ["llama3_8b", parts[6]])


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true", help="Print commands without writing the script")
    args = ap.parse_args()

    configs = set()
    for metrics in BASE.rglob("metrics.json"):
        rel = metrics.relative_to(BASE)
        # Drop version dirs (v2, v3, ...) and the leaf model/cot dirs the CLI adds
        if "llama3_8b" in rel.parts:
            continue  # already-run base-model outputs
        clean = [p for p in rel.parts if not re.fullmatch(r"v\d+", p) and p != "metrics.json"]
        if "llama3_med42_8b" in clean:
            i = clean.index("llama3_med42_8b")
            # Keep everything except the model dir itself (cot/zero_shot leaf follows it)
            configs.add(tuple(clean[:i] + clean[i + 1:]))

    lines = [
        "#!/usr/bin/env bash",
        "# Base Llama-3-8B re-runs mirroring every med42 config (reviewer request).",
        "# Generated by scripts_reviewer/generate_base_llama3_runs.py -- do not edit by hand.",
        "set -u",
        'PY=/home/ser/mambaforge/envs/medrag/bin/python',
        'cd /home/ser/medrag',
        "",
    ]
    lines += [
        "# Skip-check: exit 0 if this config already has a full 1273-question run",
        "is_done() { $PY -c \"import json,glob,sys; h=glob.glob(sys.argv[1]+'/**/metrics.json',recursive=True);"
        " sys.exit(0 if any(json.load(open(m)).get('total')==1273 for m in h) else 1)\" \"$1\"; }",
        "",
    ]
    for i, cfg in enumerate(sorted(configs), 1):
        flags = flags_for(Path(*cfg))
        assert flags, f"unmapped config: {cfg}"
        cfg_str = "/".join(cfg)
        out_rel = expected_output_dir(cfg)
        lines.append(f'echo "=== [{i}/{len(configs)}] {cfg_str} ==="')
        lines.append(f'if is_done "evaluation_results/final_output/{out_rel}"; then echo "SKIP (done): {cfg_str}"')
        lines.append(f"else $PY -m src.rag_evaluation.cli {flags} --llm-model {MODEL} || echo 'FAILED: {cfg_str}'")
        lines.append("fi")
        lines.append("")

    script = "\n".join(lines)
    if args.dry_run:
        print(script)
        return
    out = Path("/home/ser/medrag/run_base_llama3.sh")
    out.write_text(script + "\n")
    out.chmod(0o755)
    print(f"Wrote {len(configs)} commands to {out}")


if __name__ == "__main__":
    main()
